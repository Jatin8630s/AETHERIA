export function getAQICategory(aqi: number): {
  category: CityAQIData['category'];
  color: string;
  glowColor: string;
} {
  if (aqi <= 50) return { category: 'Good', color: AQI_THRESHOLDS.GOOD.color, glowColor: AQI_THRESHOLDS.GOOD.glowColor };
  if (aqi <= 100) return { category: 'Moderate', color: AQI_THRESHOLDS.MODERATE.color, glowColor: AQI_THRESHOLDS.MODERATE.glowColor };
  if (aqi <= 150) return { category: 'Unhealthy for Sensitive', color: AQI_THRESHOLDS.UNHEALTHY_SENSITIVE.color, glowColor: AQI_THRESHOLDS.UNHEALTHY_SENSITIVE.glowColor };
  if (aqi <= 200) return { category: 'Unhealthy', color: AQI_THRESHOLDS.UNHEALTHY.color, glowColor: AQI_THRESHOLDS.UNHEALTHY.glowColor };
  if (aqi <= 300) return { category: 'Very Unhealthy', color: AQI_THRESHOLDS.VERY_UNHEALTHY.color, glowColor: AQI_THRESHOLDS.VERY_UNHEALTHY.glowColor };
  return { category: 'Hazardous', color: AQI_THRESHOLDS.HAZARDOUS.color, glowColor: AQI_THRESHOLDS.HAZARDOUS.glowColor };
}

